"""Exercise the actual CLI and OCR, including a process kill after a durable start."""
import argparse
from hashlib import sha256
import json
import os
from pathlib import Path
import signal
import sqlite3
import subprocess
from tempfile import TemporaryDirectory
from zipfile import ZipFile


HERE = Path(__file__).resolve().parent


def saved_value(database,key):
    with sqlite3.connect(database) as db:
        value, = db.execute("SELECT result FROM jobs WHERE id=?",(key,)).fetchone()
    assert value
    return value


def check_rows(result):
    trace = result["trace"]
    total = sum(s["size"][0]*s["size"][1] for s in trace["steps"])
    preview = sum(s["size"][0]*s["size"][1] for s in trace.get("preview_observations",[]))
    assert 0<total+preview<=1_000_000
    assert total+preview==result["decision"]["cost"]["total"]
    assert trace["ocr_calls"]==len(trace["steps"])
    assert all(len(step["input_sha256"])==64 and "raw_normalized" in step for step in trace["steps"])
    return {"decision":result["decision"]["status"],"pixels":total+preview,"ocr_calls":trace["ocr_calls"]}


def acceptance(archive,out):
    state = out/"progress.sqlite"
    with TemporaryDirectory(dir=out) as temp:
        base = Path(temp)
        if archive:
            # The released archive is generated by pack.py with explicit paths.
            with ZipFile(archive) as release:
                release.extractall(base)
            install = base/"visual-search-batch"
        else:
            from shutil import copytree
            install = base/"visual-search-batch"
            copytree(HERE,install,ignore=lambda _,names: [
                name for name in names if name in {"pilot","验收记录","__pycache__"} or name.endswith(".zip")])
        # Running outside the extracted application directory also tests relative source resolution.
        work = base/"operator working directory"
        work.mkdir()
        shell = ["sh",str(install/"batch.sh")]
        jobs = install/"examples/jobs.json"

        def invoke(name,args,expected):
            reply = subprocess.run(shell+args,cwd=work,text=True,capture_output=True,timeout=60)
            (out/(name+".stdout")).write_text(reply.stdout)
            (out/(name+".stderr")).write_text(reply.stderr)
            assert reply.returncode==expected,(args,reply.returncode,reply.stderr)
            return reply.stdout

        run = ["run",str(jobs),"--state",str(state)]
        status = ["status","--state",str(state)]
        show = ["show","--state",str(state)]
        attempts = ["attempts","--state",str(state)]
        invoke("01-validate",["validate",str(jobs)],1)
        with (out/"02-crash.stderr").open("w") as err:
            active = subprocess.Popen(shell+run,cwd=work,stdout=subprocess.PIPE,stderr=err,
                                      text=True,start_new_session=True)
            try:
                with (out/"02-crash.jsonl").open("w") as log:
                    for line in active.stdout:
                        log.write(line)
                        item = json.loads(line)
                        if (item["event"],item.get("id"))==("started","younger-document"):
                            os.kill(active.pid,signal.SIGSTOP)
                            break
                    else:
                        raise AssertionError("Younger 的首次任务未开始")
                initial = json.loads(invoke("03-status-before-kill",status+["--json"],0))
                assert initial["counts"]==dict(pending=2,running=1,done=1,failed=1)
                original = saved_value(state,"griffith-stamp")
                blocked = "04-concurrent-run"
                invoke(blocked,run,2)
                assert "已有一个" in (out/(blocked+".stderr")).read_text()
                os.killpg(active.pid,signal.SIGKILL)
                assert active.wait(timeout=10)==-signal.SIGKILL
            finally:
                if active.poll() is None:
                    os.killpg(active.pid,signal.SIGKILL)
                    active.wait(timeout=10)
                active.stdout.close()

        resumed = [json.loads(line) for line in invoke("05-resume",run,1).splitlines()]
        assert [e["id"] for e in resumed if e["event"]=="started"]==[
            "younger-document","bad-budget","segal-stamp"]
        assert resumed[0]=={"event":"interrupted","id":"younger-document"}
        assert saved_value(state,"griffith-stamp")==original
        invoke("06-status",status,0)
        report = {}
        for key in ("griffith-stamp","younger-document","segal-stamp"):
            item = json.loads(invoke("07-proof-"+key,show+[key],0))
            report[key] = check_rows(item["result"])
        assert [item["decision"] for item in report.values()]==["verified","answered","unresolved"]
        assert report["griffith-stamp"]["pixels"]==938_863
        history = json.loads(invoke("08-attempts",attempts,0))
        assert [(a["number"],a["outcome"]) for a in history if a["job_id"]=="younger-document"]==[
            (1,"interrupted"),(2,"done")]

        noop = [json.loads(line) for line in invoke("09-noop",run,1).splitlines()]
        assert {e["event"] for e in noop}=={"skipped","batch_finished"}
        assert json.loads(invoke("10-noop-history",attempts,0))==history
        modified = jobs.with_name("modified.json")
        changed = json.loads(jobs.read_text())
        changed["jobs"][0]["text"] = "A changed task"
        modified.write_text(json.dumps(changed))
        invoke("11-changed-manifest",["run",str(modified),"--state",str(state)],2)
        assert "清单已变化" in (out/"11-changed-manifest.stderr").read_text()
        assert json.loads(invoke("12-changed-history",attempts,0))==history

        # Supply the previously absent source without editing the registered manifest.
        data = jobs.parent/"data"
        (data/"not-included.png").write_bytes((data/"griffith.png").read_bytes())
        retries = [json.loads(line) for line in invoke("13-retry",run+["--retry-failed"],1).splitlines()]
        assert [e["id"] for e in retries if e["event"]=="started"]==["missing-scan","bad-budget"]
        assert saved_value(state,"griffith-stamp")==original
        retry = json.loads(invoke("14-retried-proof",show+["missing-scan"],0))
        report["missing-scan-after-repair"] = check_rows(retry["result"])
        assert report["missing-scan-after-repair"]["decision"]=="verified"
        invoke("15-final-status",status,0)
        final = json.loads(invoke("16-final-history",attempts,0))
        assert [a["number"] for a in final if a["job_id"]=="griffith-stamp"]==[1]
        record = {
            "run_from_extracted_archive": bool(archive),
            "kill_signal": int(signal.SIGKILL),
            "same_completed_result_sha256":sha256(original.encode()).hexdigest(),
            "completed_task_not_restarted":True,"interrupted_task_retried":True,"second_run_ocr_calls":11,
            "concurrent_writer_rejected":True,"modified_manifest_rejected":True,
            "no_op_retry_runs_zero_jobs":True,"only_failed_tasks_retried":True,"results":report,
        }
        assert sum(report[k]["ocr_calls"] for k in ("younger-document","segal-stamp"))==record["second_run_ocr_calls"]
        (out/"checks.json").write_text(json.dumps(record,ensure_ascii=False,indent=2)+"\n")
        print(json.dumps(record,ensure_ascii=False,indent=2))


if __name__=="__main__":
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument("--bundle",type=Path)
    cli.add_argument("output",type=Path)
    args = cli.parse_args()
    destination = args.output.resolve()
    destination.mkdir()
    acceptance(args.bundle.resolve() if args.bundle else None,destination)
